/* Build a clean static www/ for HTTPS hosting or a future Capacitor shell.
   Keep source art, unreviewed curriculum, repositories and private local files out. */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "www");
const staging = path.join(root, `.web-build-${process.pid}`);
const previous = path.join(root, `.web-backup-${process.pid}`);
const marker = ".picture-english-build";
const copied = [];
const top = ["index.html", "offline.html", "manifest.webmanifest", "service-worker.js", "shell.css", "rpg.css", "atlas.css", "world.js", "battle.js", "learn.js", "novice.js", "lifescene.js", "pron.js", "speech.js", "rpg.js", "atlas.js", "platform.js"];
const assetRoots = ["sprites", "voice", "scenes", "app", "images", "sfx", "bgm", "video"];
async function exists(p) { try { await fs.access(p); return true; } catch (_) { return false; } }
async function copy(relative, destination = relative) {
  const source = path.join(root, relative);
  const stat = await fs.lstat(source);
  if (stat.isSymbolicLink() || !stat.isFile()) throw new Error(`Expected a regular source file: ${relative}`);
  const dest = path.join(staging, destination);
  await fs.mkdir(path.dirname(dest), { recursive: true });
  await fs.copyFile(source, dest);
  copied.push(destination);
}
async function tree(relative) {
  if (!await exists(path.join(root, relative))) return;
  const entries = await fs.readdir(path.join(root, relative), { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith(".")) continue;
    const p = path.join(relative, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Refusing symlink: ${p}`);
    if (entry.isDirectory()) await tree(p);
    else await copy(p);
  }
}
async function validate() {
  const html = await fs.readFile(path.join(staging, "index.html"), "utf8");
  for (const match of html.matchAll(/<(?:script|link)\b[^>]*(?:src|href)="([^"]+)"/g)) {
    if (/^(?:https?:|\/\/|data:)/.test(match[1])) continue;
    const relative = match[1].replace(/^\.\//, "").split(/[?#]/)[0];
    if (!await exists(path.join(staging, relative))) throw new Error(`HTML references missing file: ${relative}`);
  }
  const scenes = JSON.parse(await fs.readFile(path.join(staging, "data/life-scenes.json"), "utf8"));
  for (const scene of scenes.scenes) {
    if (!await exists(path.join(staging, scene.image))) throw new Error(`Missing scene image: ${scene.image}`);
  }
  const manifest = JSON.parse(await fs.readFile(path.join(staging, "manifest.webmanifest"), "utf8"));
  for (const icon of manifest.icons) if (!await exists(path.join(staging, icon.src))) throw new Error(`Missing icon: ${icon.src}`);
  const assets = JSON.parse(await fs.readFile(path.join(staging, "assets/manifest.json"), "utf8"));
  for (const group of Object.values(assets)) if (group && typeof group === "object") {
    for (const item of Object.values(group)) if (item && typeof item === "object" && item.file && !/^(?:https?:|data:)/.test(item.file) && !await exists(path.join(staging, item.file))) throw new Error(`Missing manifest asset: ${item.file}`);
  }
}

let oldMoved = false;
try {
  if (await exists(output)) {
    const stat = await fs.lstat(output);
    if (stat.isSymbolicLink() || !await exists(path.join(output, marker))) throw new Error("www/ exists without the build marker; preserve it and choose a clean output directory.");
  }
  if (await exists(staging) || await exists(previous)) throw new Error("A build working directory already exists; inspect it before retrying.");
  await fs.mkdir(staging);
  for (const name of top) await copy(name);
  await tree("data");
  await copy("assets/manifest.json");
  for (const name of assetRoots) await tree(path.join("assets", name));
  await copy("content/core-3000/sources/ECDICT-LICENSE.txt", "THIRD_PARTY_LICENSES/ECDICT-LICENSE.txt");
  await validate();
  const digest = createHash("sha256");
  for (const name of copied.slice().sort()) digest.update(name).update(await fs.readFile(path.join(staging, name)));
  const version = "web-" + digest.digest("hex").slice(0, 16);
  const swPath = path.join(staging, "service-worker.js");
  const sw = await fs.readFile(swPath, "utf8");
  if (!/const VERSION = "[^"]+";/.test(sw)) throw new Error("Service worker version marker missing.");
  await fs.writeFile(swPath, sw.replace(/const VERSION = "[^"]+";/, `const VERSION = "${version}";`));
  await fs.writeFile(path.join(staging, marker), "Generated by tools/build_web.mjs; source files stay in the project root.\n");
  await fs.writeFile(path.join(staging, "build-info.json"), JSON.stringify({ version, fileCount: copied.length, generatedAt: new Date().toISOString(), nativeBuild: false }, null, 2) + "\n");
  if (await exists(output)) { await fs.rename(output, previous); oldMoved = true; }
  await fs.rename(staging, output);
  if (oldMoved) await fs.rm(previous, { recursive: true });
  console.log(`Built ${copied.length} runtime files into www/ (${version}); source artwork and draft curriculum excluded. This is a web build, not an APK or IPA.`);
} catch (error) {
  if (oldMoved && !await exists(output)) await fs.rename(previous, output);
  if (await exists(staging)) await fs.rm(staging, { recursive: true });
  console.error(error.message);
  process.exitCode = 1;
}
